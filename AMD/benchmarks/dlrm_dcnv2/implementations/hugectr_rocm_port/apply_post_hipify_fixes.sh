#!/usr/bin/env bash
# Apply mechanical post-hipify substitutions for the HugeCTR -> ROCm port.
# Operates in-place on /apps/chcai/hugectr_rocm_port/hugectr_hip/.
# All edits are conservative one-liners corresponding to known hipify-perl warnings.
set -u

ROOT=/apps/chcai/hugectr_rocm_port/hugectr_hip

apply() {
    local desc="$1" pattern="$2" replacement="$3"
    shift 3
    local files=("$@")
    local n=0
    for f in "${files[@]}"; do
        if [[ -f "$f" ]] && grep -qE "$pattern" "$f" 2>/dev/null; then
            sed -i -E "s|$pattern|$replacement|g" "$f"
            n=$((n + 1))
        fi
    done
    printf "  %-55s patched in %d files\n" "$desc" "$n"
}

echo "=== mechanical post-hipify fixes ==="

# (A) cuBLAS Tensor-Op algo enums -> default. hipBLAS doesn't expose alg-specific
#     tensor-op flavors; default selection is fine for correctness. Perf can be
#     re-tuned later via hipBLASLt or rocBLAS algorithm querying.
apply "CUBLAS_GEMM_DEFAULT_TENSOR_OP -> HIPBLAS_GEMM_DEFAULT" \
      'CUBLAS_GEMM_DEFAULT_TENSOR_OP' 'HIPBLAS_GEMM_DEFAULT' \
      $ROOT/HugeCTR/src/layers/fully_connected_layer.cu \
      $ROOT/HugeCTR/src/layers/fully_connected_layer_half.cu \
      $ROOT/HugeCTR/src/layers/interaction_layer.cu \
      $ROOT/HugeCTR/src/layers/multi_head_attention_layer.cu

apply "CUBLAS_GEMM_ALGO15_TENSOR_OP -> HIPBLAS_GEMM_DEFAULT" \
      'CUBLAS_GEMM_ALGO15_TENSOR_OP' 'HIPBLAS_GEMM_DEFAULT' \
      $ROOT/HugeCTR/src/layers/fully_connected_layer.cu \
      $ROOT/HugeCTR/src/layers/fully_connected_layer_half.cu

apply "CUBLAS_GEMM_ALGO23 -> HIPBLAS_GEMM_DEFAULT" \
      'CUBLAS_GEMM_ALGO23' 'HIPBLAS_GEMM_DEFAULT' \
      $ROOT/HugeCTR/src/layers/fully_connected_layer.cu

# (B) cudaEventWaitExternal flag (CUDA Graphs) doesn't exist in HIP graphs.
#     Default flag (0) is correct for non-graph semantics.
apply "cudaEventWaitExternal -> 0" \
      'cudaEventWaitExternal' '0' \
      $ROOT/HugeCTR/src/pipeline.cpp \
      $ROOT/HugeCTR/src/data_readers/multi_hot/async_data_reader.cpp

apply "cudaEventWaitDefault -> 0" \
      'cudaEventWaitDefault' '0' \
      $ROOT/HugeCTR/src/pipeline.cpp

# (C) CUDA driver attribute for memory compression -> assume unsupported.
apply "CU_DEVICE_ATTRIBUTE_GENERIC_COMPRESSION_SUPPORTED -> 0" \
      'CU_DEVICE_ATTRIBUTE_GENERIC_COMPRESSION_SUPPORTED' '0' \
      $ROOT/HugeCTR/core23/details/low_level_cuda_allocator.cpp

# (D) HierarchicalKV unsupported intrinsics.
#     __stwt(ptr, val) -> non-temporal store, available via builtin.
#     __vcmpeq4(a, b)  -> emulate per-byte equality across 32-bit lanes.
echo "  (HierarchicalKV intrinsics will be patched via header injection below)"

cat > $ROOT/third_party/HierarchicalKV/include/merlin/_hip_compat.h <<'HDR'
// HIP compatibility shims for HierarchicalKV CUDA intrinsics.
// Auto-generated by post-hipify fixup script.
#pragma once
#ifdef __HIPCC__

#ifndef HKV_HIP_INTRINSIC_SHIMS
#define HKV_HIP_INTRINSIC_SHIMS

// __stwt: non-temporal (streaming) global store.
// HIP/AMDGPU: use __builtin_nontemporal_store, available in clang.
template <typename T>
__device__ __forceinline__ void __stwt(T* dst, T val) {
  __builtin_nontemporal_store(val, dst);
}

// __vcmpeq4: byte-wise equality on packed 4-byte words. Returns a 32-bit mask
// where each byte lane is 0xFF (equal) or 0x00 (not equal). Compatible with
// CUDA's vector compare semantics used by HierarchicalKV digest probing.
__device__ __forceinline__ unsigned int __vcmpeq4(unsigned int a, unsigned int b) {
  unsigned int x = a ^ b;
  // Each byte == 0 iff a == b for that byte. Set lanes via 0x80808080 trick.
  unsigned int t = (x | (x >> 1));
  t = (t | (t >> 2));
  t = (t | (t >> 4));            // each byte: high bit set iff any nonzero bit
  t &= 0x01010101u;              // collapse to per-byte zero/one indicator
  unsigned int eq = t ^ 0x01010101u; // 1 per byte if equal, 0 otherwise
  return eq * 0xFFu;             // expand each byte 1 -> 0xFF, 0 -> 0x00
}

#endif // HKV_HIP_INTRINSIC_SHIMS
#endif // __HIPCC__
HDR
echo "  injected _hip_compat.h"

# Make sure utils.cuh in HierarchicalKV picks up the shims early
UTILS=$ROOT/third_party/HierarchicalKV/include/merlin/utils.cuh
if [[ -f "$UTILS" ]] && ! grep -q '_hip_compat.h' "$UTILS"; then
    sed -i '1i #include "_hip_compat.h"' "$UTILS"
    echo "  added shim include to merlin/utils.cuh"
fi

echo ""
echo "=== verify no remaining mechanical residue ==="
total=0
for kw in CUBLAS_GEMM_DEFAULT_TENSOR_OP CUBLAS_GEMM_ALGO15_TENSOR_OP CUBLAS_GEMM_ALGO23 \
          cudaEventWaitExternal cudaEventWaitDefault \
          CU_DEVICE_ATTRIBUTE_GENERIC_COMPRESSION_SUPPORTED; do
    n=$(grep -rln "$kw" $ROOT \
        --include='*.cu' --include='*.cuh' --include='*.cpp' --include='*.hpp' --include='*.h' \
        2>/dev/null | wc -l)
    printf "  remaining %-55s in %d files\n" "$kw" "$n"
    total=$((total + n))
done
echo ""
echo "TOTAL remaining mechanical residue: $total files"
